#!/usr/bin/env bash
# Writes a lab-int release on the "deploy" branch: the commit Portainer follows (it polls the
# branch and redeploys the stack when the commit changes). Run by the CI only after both images
# of the commit are on GHCR, so Portainer never sees a release whose images do not exist yet.
#
#   deploy/release-lab-int.sh <full commit SHA>
#
# The branch has a history of its own (no source code): one plain commit per release, never a
# force push. Its files are generated from the commit being released, so they follow main
# without manual edits:
#   docker-compose.yml  main's compose, with HOMETAB_IMAGE_TAG replaced by the SHA (a literal
#                       tag: a variable left in Portainer cannot override it)
#   RELEASE             the SHA, read back by the next release
#   README.md           what the branch is
# Rolling back is a "git revert" on the branch; the next release from main goes forward again.
set -euo pipefail

sha="${1:-}"
branch="${DEPLOY_BRANCH:-deploy}"
remote="${DEPLOY_REMOTE:-origin}"

if [[ ! "$sha" =~ ^[0-9a-f]{40}$ ]]; then
  echo "Usage: $0 <full commit SHA>" >&2
  exit 1
fi

root="$(git rev-parse --show-toplevel)"
cd "$root"
git cat-file -e "$sha^{commit}"

work="$(mktemp -d)"
cleanup() {
  git worktree remove --force "$work" >/dev/null 2>&1 || true
  git branch -D "release-${sha:0:7}" >/dev/null 2>&1 || true
  rm -rf "$work"
}
trap cleanup EXIT

render() {
  local out="$1"
  {
    echo "# GENERATED by deploy/release-lab-int.sh from commit $sha: do not edit."
    echo "# Source: docker-compose.yml on main, with HOMETAB_IMAGE_TAG pinned to the commit SHA."
    echo
    git show "$sha:docker-compose.yml" | sed "s/\${HOMETAB_IMAGE_TAG:-main}/$sha/g"
  } >"$out/docker-compose.yml"

  # If main changes how the tag is written, stop here instead of deploying "main" by accident.
  if grep -vE '^\s*#' "$out/docker-compose.yml" | grep -q 'HOMETAB_IMAGE_TAG'; then
    echo "docker-compose.yml still references HOMETAB_IMAGE_TAG: update the substitution." >&2
    exit 1
  fi
  local images pinned
  images="$(grep -cE '^\s*image:\s*ghcr\.io/' "$out/docker-compose.yml" || true)"
  pinned="$(grep -cE "^\s*image:\s*ghcr\.io/[^[:space:]]+:$sha\s*$" "$out/docker-compose.yml" || true)"
  if [[ "$images" -eq 0 || "$images" -ne "$pinned" ]]; then
    echo "Expected every GHCR image pinned to $sha ($pinned of $images)." >&2
    exit 1
  fi

  echo "$sha" >"$out/RELEASE"

  cat >"$out/README.md" <<'EOF'
# deploy

Generated branch, written by the CI (`deploy/release-lab-int.sh` on `main`): do not edit.

Each commit is a release of the local production instance, made only after the images of that
commit have been published to GHCR. The Portainer stack follows this branch and redeploys
when it changes.

- `docker-compose.yml`: the compose file of `main` with the image tag pinned to the commit SHA
- `RELEASE`: the SHA of the release

Roll back with `git revert` on this branch; the next push to `main` releases again.
EOF
}

subject="$(git log -1 --format=%s "$sha")"
short="${sha:0:7}"
message="$(
  printf 'Release %s: %s\n\n' "$short" "$subject"
  printf 'Images: hometab-app:%s, hometab-mongodb:%s\n' "$sha" "$sha"
  if [[ -n "${GITHUB_REPOSITORY:-}" ]]; then
    printf 'Source: %s/%s/commit/%s\n' "${GITHUB_SERVER_URL:-https://github.com}" "$GITHUB_REPOSITORY" "$sha"
    [[ -n "${GITHUB_RUN_ID:-}" ]] &&
      printf 'CI run: %s/%s/actions/runs/%s\n' "${GITHUB_SERVER_URL:-https://github.com}" "$GITHUB_REPOSITORY" "$GITHUB_RUN_ID"
  fi
  printf '\nSource-Commit: %s\n' "$sha"
)"

# A push can lose a race (another release, a manual revert): fetch again and retry.
for attempt in 1 2 3 4 5; do
  if git ls-remote --exit-code --heads "$remote" "$branch" >/dev/null; then
    git fetch --quiet "$remote" "+refs/heads/$branch:refs/remotes/$remote/$branch"
    git worktree add --quiet --detach "$work" "refs/remotes/$remote/$branch"
    current="$(cat "$work/RELEASE" 2>/dev/null || true)"
    # Never go back in time: skip if this commit is already released or older than the release.
    if [[ -n "$current" ]] && git merge-base --is-ancestor "$sha" "$current" 2>/dev/null; then
      echo "Release $current already includes $sha: nothing to do."
      exit 0
    fi
  else
    # First release: a branch with no parent, unrelated to main.
    git worktree add --quiet --detach "$work" HEAD
    git -C "$work" checkout --quiet --orphan "release-$short"
    git -C "$work" rm -r --quiet --force .
  fi

  render "$work"
  git -C "$work" add -A
  if git -C "$work" diff --cached --quiet; then
    echo "Branch $branch already matches $sha: nothing to do."
    exit 0
  fi
  git -C "$work" commit --quiet -m "$message"
  if git -C "$work" push --quiet "$remote" "HEAD:refs/heads/$branch"; then
    echo "Released $sha on $branch ($(git -C "$work" rev-parse --short HEAD))."
    exit 0
  fi

  echo "Push rejected (attempt $attempt): retrying." >&2
  git worktree remove --force "$work"
  git branch -D "release-$short" >/dev/null 2>&1 || true
  sleep $((attempt * 5))
done

echo "Could not push the release after 5 attempts." >&2
exit 1
